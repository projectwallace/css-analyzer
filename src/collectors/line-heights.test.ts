import { test, expect, describe } from 'vitest'
import { analyze } from '../engine/analyzer.ts'
import { plain } from '../test/test-utils.ts'
import { line_heights } from './line-heights.ts'

function run(css: string) {
	return plain(analyze(css, { result: line_heights() }).result)
}

test('recognizes line-height', () => {
	const fixture = `
    test {
      line-height: 1;
			line-height: 100%;
			line-height: calc(1em + 2vh);
			line-height: 2em;
			line-height: normal;
      /* Unrelated */
      color: brown;
      font-size: 12px;
    }
  `
	const actual = run(fixture)
	const expected = {
		total: 5,
		total_unique: 5,
		unique: {
			'1': 1,
			'100%': 1,
			'calc(1em + 2vh)': 1,
			'2em': 1,
			normal: 1,
		},
	}

	expect(actual).toEqual(expected)
})

test('extracts the `font` shorthand', () => {
	const fixture = `
    test {
      font: large 'Noto Sans';
      font: normal normal 1em/1 "Source Sans Pro", serif;
      font: normal normal 1.2em serif;
      font: 400 1.3em/1 serif;
      font: 1em / 1 serif;
      font: 1em/ 1 serif;
      font: 1em /1 serif;
      font: normal normal 11px/1.5 -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif, "Apple Color Emoji", "Segoe UI Emoji", "Segoe UI Symbol";
      font: 11px Consolas, "Liberation Mono", Menlo, Courier, monospace;
      font: 0/0 a; /* As generated by some css minifiers */
      /* Unrelated */
      color: brown;
      font-size: 12px;
    }
  `
	const actual = run(fixture)
	const expected = {
		total: 7,
		total_unique: 3,
		unique: {
			'1': 5,
			'1.5': 1,
			'0': 1,
		},
	}
	expect(actual).toEqual(expected)
})

describe('normalizing', () => {
	test('line-height', () => {
		const actual = run(`test { line-height: 1EM }`).unique
		expect(actual).toEqual({ '1em': 1 })
	})

	test('font shorthand', () => {
		const actual = run(`test { font: 10PX/1EM serif }`).unique
		expect(actual).toEqual({ '1em': 1 })
	})

	test('leaves var() intact', () => {
		const actual = run(`test {
			line-height: var(--lineHeight1);
			line-height: VAR(--lineHeight2);
		}`).unique
		expect(actual).toEqual({
			'var(--lineHeight1)': 1,
			'VAR(--lineHeight2)': 1,
		})
	})
})

test('handles system fonts', () => {
	// Source: https://drafts.csswg.org/css-fonts-3/#font-prop
	const fixture = `
    test {
      font: menu;        /* use the font settings for system menus */
      font: large menu;  /* use a font family named "menu" */
    }
  `
	const actual = run(fixture)
	const expected = {
		total: 0,
		total_unique: 0,
		unique: {},
	}

	expect(actual).toEqual(expected)
})

test('ignores keywords and global values', () => {
	const fixture = `
		test {
			/* Global values */
			line-height: inherit;
			line-height: initial;
			line-height: revert;
			line-height: revert-layer;
			line-height: unset;

      font: inherit;
      font: initial;
      font: revert;
      font: revert-layer;
      font: unset;
		}
	`
	const actual = run(fixture)
	const expected = {
		total: 0,
		total_unique: 0,
		unique: {},
	}

	expect(actual).toEqual(expected)
})
